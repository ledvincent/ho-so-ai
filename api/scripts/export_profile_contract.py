"""Generate the browser's nullable profile fields/bounds from the API model."""

import argparse
import json
from pathlib import Path
import sys

api_root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(api_root))
from hoso_api.profile import ProfileFields  # noqa: E402


def generated_contract() -> str:
    properties = ProfileFields.model_json_schema()['properties']
    lines = ['// Generated by api/scripts/export_profile_contract.py. Do not edit by hand.', 'export type ProfileFields = {']
    limits = {}
    for name, specification in properties.items():
        variants = specification.get('anyOf', [])
        if {variant.get('type') for variant in variants} != {'string', 'null'}:
            raise ValueError('Update the generator for the new profile field shape.')
        text = next(variant for variant in variants if variant.get('type') == 'string')
        lines.append(f'  {json.dumps(name)}: string | null;')
        if 'maxLength' in text:
            limits[name] = text['maxLength']
    lines.extend(['};', f'export const PROFILE_LIMITS = {json.dumps(limits)} as const;', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    target = api_root.parent / 'web' / 'lib' / 'profile.generated.ts'
    expected = generated_contract()
    if arguments.check:
        if not target.exists() or target.read_text(encoding='utf-8') != expected:
            raise SystemExit('Profile contract differs. Run api/scripts/export_profile_contract.py and commit both sides.')
        print('Profile contract matches the API model.')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding='utf-8', newline='\n')
        print('Generated web/lib/profile.generated.ts from the API model.')
