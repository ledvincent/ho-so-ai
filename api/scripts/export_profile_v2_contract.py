"""Generate additive profile/prefill TypeScript from the API's Pydantic schemas."""

import argparse
import json
from pathlib import Path
import sys

api_root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(api_root))
from hoso_api.profile_v2_models import ProfileDetails, ProfileV2Update, ProfileV2Response
from hoso_api.profile_prefill import PrefillRequest, PrefillResponse


def generate() -> str:
    definitions = {}
    for model in (ProfileDetails, ProfileV2Update, ProfileV2Response, PrefillRequest, PrefillResponse):
        schema = model.model_json_schema()
        for name, value in schema.pop('$defs', {}).items():
            if name in definitions and definitions[name] != value:
                raise ValueError('Conflicting generated schema definition.')
            definitions[name] = value
        definitions[model.__name__] = schema

    def ts(schema):
        if '$ref' in schema:
            return schema['$ref'].split('/')[-1]
        if 'const' in schema:
            return json.dumps(schema['const'])
        if 'enum' in schema:
            return ' | '.join(json.dumps(value) for value in schema['enum'])
        if 'anyOf' in schema:
            return ' | '.join(ts(item) for item in schema['anyOf'])
        kind = schema.get('type')
        if kind == 'null': return 'null'
        if kind == 'string': return 'string'
        if kind in ('integer', 'number'): return 'number'
        if kind == 'boolean': return 'boolean'
        if kind == 'array': return f'Array<{ts(schema["items"])}>'
        if kind == 'object':
            if 'properties' in schema:
                required = schema.get('required', [])
                fields = [f'  {json.dumps(name)}{"" if name in required else "?"}: {ts(value)};'
                          for name, value in schema['properties'].items()]
                return '{\n' + '\n'.join(fields) + '\n}'
            extra = schema.get('additionalProperties')
            return f'Record<string, {ts(extra) if isinstance(extra, dict) else "unknown"}>'
        raise ValueError('Unsupported schema shape in contract generator.')

    limits = {}
    def collect(schema, path=''):
        if '$ref' in schema:
            return collect(definitions[schema['$ref'].split('/')[-1]], path)
        for variant in schema.get('anyOf', []): collect(variant, path)
        if 'maxLength' in schema: limits[path] = schema['maxLength']
        for name, value in schema.get('properties', {}).items(): collect(value, f'{path}.{name}'.strip('.'))
    collect(definitions['ProfileDetails'])
    blank = ProfileDetails(basics={}, contact={}, passport={}, residence={}).model_dump()
    lines = ['// Generated by api/scripts/export_profile_v2_contract.py. Do not edit by hand.']
    lines += [f'export type {name} = {ts(schema)};' for name, schema in definitions.items()]
    lines += [f'export const PROFILE_V2_LIMITS = {json.dumps(limits, ensure_ascii=True)} as const;',
              f'export const EMPTY_PROFILE_DETAILS = {json.dumps(blank, ensure_ascii=True)} as const satisfies ProfileDetails;', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = api_root.parent / 'web/lib/profile-v2.generated.ts'
    expected = generate()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != expected:
            raise SystemExit('Profile v2 contract differs; regenerate and commit the API and browser contract together.')
        print('Profile v2 contract matches the API models.')
    else:
        target.write_text(expected, encoding='utf-8', newline='\n')
        print('Generated web/lib/profile-v2.generated.ts.')
